const isLang = (lang) => LANGS.includes(lang);

/** Pure: the text for key in lang, with {name} placeholders filled from vars. Falls back to Arabic, then to the key. */
function translate(lang, key, vars = {}) {
  const table = STRINGS[isLang(lang) ? lang : DEFAULT_LANG];
  const raw = table[key] !== undefined ? table[key] : (STRINGS[DEFAULT_LANG][key] !== undefined ? STRINGS[DEFAULT_LANG][key] : key);
  return raw.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
}

/** Pure: the path a link should use in lang ('/pricing' -> '/en/pricing' in English; '/' -> '/en'). Non-localized paths stay as they are. */
function localizedPath(lang, path) {
  if (lang !== 'en' || !LOCALIZED_PATHS.includes(path)) return path;
  return path === '/' ? '/en' : `/en${path}`;
}

/** Pure: splits a request path into its language and the path without the /en prefix. */
function splitPath(path) {
  if (path === '/en' || path === '/en/') return { lang: 'en', path: '/' };
  if (path.startsWith('/en/')) return { lang: 'en', path: path.slice(3) };
  return { lang: DEFAULT_LANG, path };
}

/** Pure: "أ، ب وج" in Arabic, "a, b and c" in English. */
function joinList(lang, items) {
  if (items.length <= 1) return items.join('');
  const sep = lang === 'en' ? ', ' : '، ';
  return `${items.slice(0, -1).join(sep)}${translate(lang, 'list.and')}${items[items.length - 1]}`;
}

module.exports = { LANGS, DEFAULT_LANG, LOCALIZED_PATHS, STRINGS, translate, localizedPath, splitPath, joinList, isLang };
